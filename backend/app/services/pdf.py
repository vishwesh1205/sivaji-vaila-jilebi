import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from sqlalchemy.orm import Session

from .. import models
from ..services.provenance import case_lineage, verify_audit_chain
from ..services.risk import compute_institution_risk


TEAL = colors.HexColor("#1E8E73")
NAVY = colors.HexColor("#102A43")
AMBER = colors.HexColor("#8A4A17")


def _styles():
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="AICTEH1", parent=styles["Heading1"], textColor=NAVY, fontSize=18, spaceAfter=8))
    styles.add(ParagraphStyle(name="AICTEH2", parent=styles["Heading2"], textColor=NAVY, fontSize=12, spaceBefore=10, spaceAfter=4))
    styles.add(ParagraphStyle(name="AICTEBody", parent=styles["BodyText"], fontSize=8.5, leading=11))
    styles.add(ParagraphStyle(name="AICTESmall", parent=styles["BodyText"], fontSize=7, leading=9, textColor=colors.HexColor("#667585")))
    styles.add(ParagraphStyle(name="AICTEAmber", parent=styles["BodyText"], fontSize=8.5, textColor=AMBER))
    return styles


def _doc(buffer):
    return SimpleDocTemplate(buffer, pagesize=A4, rightMargin=15 * mm, leftMargin=15 * mm, topMargin=14 * mm, bottomMargin=14 * mm, title="AICTE Complaint Monitoring", author="AICTE Dashboard (draft)")


def _kv_table(rows):
    data = [[str(k), str(v)] for k, v in rows]
    t = Table(data, colWidths=[48 * mm, 130 * mm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("TEXTCOLOR", (0, 0), (0, -1), NAVY),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("LINEBELOW", (0, 0), (-1, -2), 0.25, colors.HexColor("#E7ECF1")),
    ]))
    return t


def build_evidence_pack(db: Session, alert: models.OverlapAlert) -> bytes:
    styles = _styles()
    buf = io.BytesIO()
    doc = _doc(buf)
    story = [
        Paragraph("Evidence Pack – Overlap Alert", styles["AICTEH1"]),
        Paragraph("Draft for officer review. Generated by the AICTE Integrated Complaint Monitoring Dashboard. Synthetic demo data is labeled.", styles["AICTESmall"]),
        Spacer(1, 6),
    ]
    inst = alert.institution
    story.append(_kv_table([
        ("Alert ID", alert.id),
        ("Institution", f"{inst.name} ({inst.aicte_permanent_id})" if inst else "Unknown"),
        ("Bureaus involved", ", ".join(alert.bureaus_involved)),
        ("Status", alert.status.value),
        ("Why flagged", alert.why_flagged),
        ("Generated", datetime.utcnow().isoformat() + " UTC"),
    ]))
    story.append(Paragraph("Cases", styles["AICTEH2"]))
    for cid in alert.case_ids:
        c = db.get(models.Case, cid)
        if not c:
            continue
        lineage = case_lineage(db, c)
        story.append(Paragraph(escape(f"{c.case_id} · {c.bureau.code if c.bureau else ''} · {c.category.value} · {c.status.value}"), styles["AICTEBody"]))
        story.append(_kv_table([
            ("Source", f"{c.source_name or 'manual'} / {c.source_type}"),
            ("Raw payload hash", (lineage["stage_1_raw_payload"].get("payload_sha256") or "not retained")),
            ("Raw institution text", c.raw_institution_text),
            ("Narrative", (c.narrative[:400] + "...") if len(c.narrative) > 400 else c.narrative),
            ("Resolution", f"{c.resolution_status.value} at confidence {c.match_confidence:.2f}"),
            ("Audit chain valid", str(verify_audit_chain(db, c.id))),
        ]))
        story.append(Spacer(1, 5))
    story.append(Paragraph("Merged action timeline", styles["AICTEH2"]))
    timeline = []
    for cid in alert.case_ids:
        c = db.get(models.Case, cid)
        if not c:
            continue
        for a in c.actions:
            timeline.append((a.created_at, c.case_id, a.action_type.value, a.actor.name if a.actor else "system", a.remarks))
    timeline.sort(key=lambda x: x[0])
    data = [["Time", "Case", "Action", "Actor", "Remarks"]]
    for row in timeline[:40]:
        data.append([row[0].strftime("%Y-%m-%d %H:%M"), row[1], row[2], row[3], (row[4] or "")[:80]])
    table = Table(data, colWidths=[28 * mm, 28 * mm, 28 * mm, 28 * mm, 66 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8F6F1")),
        ("TEXTCOLOR", (0, 0), (-1, 0), NAVY),
        ("FONTSIZE", (0, 0), (-1, -1), 6.5),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E7ECF1")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(table)
    story.append(Paragraph("This pack links raw payload hashes, resolution decisions, and the overlap rule. Downloading it does not modify the audit chain.", styles["AICTESmall"]))
    doc.build(story)
    return buf.getvalue()


def build_institution_brief(db: Session, inst: models.Institution) -> bytes:
    styles = _styles()
    buf = io.BytesIO()
    doc = _doc(buf)
    risk = compute_institution_risk(db, inst.id)
    cases = inst.cases
    active = [c for c in cases if c.status in {models.CaseStatus.PENDING, models.CaseStatus.UNDER_PROCESS, models.CaseStatus.ESCALATED}]
    alerts = db.query(models.OverlapAlert).filter(models.OverlapAlert.institution_id == inst.id).all() if hasattr(db, "query") else []
    story = [
        Paragraph("Institution Brief for the Competent Authority", styles["AICTEH1"]),
        Paragraph("DRAFT FOR OFFICER REVIEW · Not a final regulatory finding", styles["AICTEAmber"]),
        Spacer(1, 4),
    ]
    story.append(_kv_table([
        ("Institution", inst.name),
        ("AICTE Permanent ID", inst.aicte_permanent_id),
        ("Address", inst.address),
        ("Region / State", f"{inst.region} / {inst.state}"),
        ("Approval status", inst.approval_status),
        ("Data provenance", f"{inst.source_type}; synthetic={inst.is_synthetic}"),
        ("Risk score", f"{risk['score']} / 100"),
    ]))
    story.append(Paragraph("Risk score breakdown", styles["AICTEH2"]))
    rdata = [["Component", "Raw", "Weight", "Points"]]
    for row in risk["breakdown"]:
        rdata.append([row["component"], row["explanation"], row["weight"], row["points"]])
    t = Table(rdata, colWidths=[60 * mm, 50 * mm, 30 * mm, 30 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8F6F1")), ("FONTSIZE", (0, 0), (-1, -1), 7.5), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E7ECF1"))]))
    story.append(t)
    story.append(Paragraph("Active cases by bureau", styles["AICTEH2"]))
    cdata = [["Case", "Bureau", "Category", "Age(days)", "Last action"]]
    for c in active[:20]:
        cdata.append([c.case_id, c.bureau.code if c.bureau else "", c.category.value, (datetime.utcnow() - c.date_received).days, (c.last_action_text or "")[:60]])
    ct = Table(cdata, colWidths=[33 * mm, 20 * mm, 35 * mm, 20 * mm, 65 * mm])
    ct.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8F6F1")), ("FONTSIZE", (0, 0), (-1, -1), 6.8), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E7ECF1")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(ct)
    story.append(Paragraph("Overlap alerts", styles["AICTEH2"]))
    if alerts:
        for a in alerts[-5:]:
            story.append(Paragraph(escape(f"Alert {a.id}: {a.why_flagged} ({a.status.value})"), styles["AICTEBody"]))
    else:
        story.append(Paragraph("No overlap alerts.", styles["AICTEBody"]))
    story.append(Paragraph("Recommended coordination steps (rule-generated)", styles["AICTEH2"]))
    steps = []
    if alerts:
        steps.append("Convene a joint review across the bureaus named in the open overlap alert(s).")
    if any(c.status == models.CaseStatus.ESCALATED for c in cases):
        steps.append("Prioritise escalated cases and record a disposal plan.")
    if any((datetime.utcnow() - c.date_received).days >= 90 and c.status != models.CaseStatus.DISPOSED for c in cases):
        steps.append("Resolve cases beyond the 90-day outer limit; issue an interim status note.")
    steps.append("Verify the latest facts against the raw payloads using the provenance trace before any regulatory action.")
    for s in steps:
        story.append(Paragraph(escape("• " + s), styles["AICTEBody"]))
    story.append(Spacer(1, 8))
    story.append(Paragraph("Assumptions: synthetic/demo records may be present and are labeled at source. This brief is generated from the current database snapshot and must be reviewed by an officer.", styles["AICTESmall"]))
    doc.build(story)
    return buf.getvalue()
